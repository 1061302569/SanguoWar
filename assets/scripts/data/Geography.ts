/**
 * 三国时期的地理要素（简化）
 *
 * ─── 为什么用「海面多边形」而不是「陆地多边形」 ───
 *   中国东部海岸有渤海湾、山东半岛、雷州半岛等多处凹陷，
 *   一个自相交的陆地多边形会导致填充出现破洞。
 *   改为先铺陆地、再盖海面，只要海面多边形不自相交就绝对安全。
 *
 * ─── 海面多边形怎么保证不自相交 ───
 *   海岸线严格「从北向南」排列（纬度单调递减），
 *   闭合时从最南端拉到地图东南角、再拉到东北角、回到最北端。
 *   这样形成的是一个简单的开口朝西的区域，绝不会自相交。
 *
 * 数据精度是「可辨识」级（约 50 个海岸控制点）。
 */

