/**
 * 构造陆地多边形
 *
 * 海岸线从北向南走完，再沿地图西边界绕回，形成一个简单多边形：
 *   海岸线首点（东北，约 42.5°N）
 *     → 海岸线一路向南
 *     → 海岸线末点（西南，约 18.6°N）
 *     → 左下角
 *     → 左上角
 *     → 回到海岸线首点（闭合）
 *
 * 注意闭合时要从「左上角」连回「海岸线首点」，中间这段是北部边界。
 * 如果直接让多边形用首尾相连闭合，顶部的纬度区间（42.5°~43°N）会露在海里。
 */
export function buildLandPolygon(
    lonMin: number, latMin: number, latMax: number,
): Array<[number, number]> {
    const land: Array<[number, number]> = COASTLINE.slice();
    land.push([lonMin, latMin]);          // 左下角
    land.push([lonMin, latMax]);          // 左上角
    // 沿地图上边界向东，接回海岸线首点，补齐北部陆地
    land.push([COASTLINE[0][0], latMax]);
    return land;
}

